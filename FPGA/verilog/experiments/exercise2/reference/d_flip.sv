/*
 * Dフリップフロップ (D Flip-Flop)
 * クロックの立ち上がりエッジで入力を保持する基本的なメモリ要素
 */

// モジュール宣言: デザインの境界を定義
module d_flipflop (
    // ポート（入出力信号）の定義
    input  logic clk,      // クロック入力
    input  logic rst_n,    // 非同期リセット（アクティブ・ロー）
    input  logic d,        // データ入力
    output logic q         // データ出力
);

    // ----------------------------------------------------
    // ハードウェア動作記述
    // ----------------------------------------------------

    // sequentialブロック (always_ff): 順序回路（フリップフロップやレジスタ）の記述に使用
    // クロック、または非同期リセットのエッジをトリガとして指定
    always_ff @(posedge clk or negedge rst_n) begin
        // 非同期リセット処理
        if (rst_n == 1'b0) begin
            // rst_n が 0（アクティブ・ロー）の場合、出力を 0 にリセット
            q <= 1'b0;
        end
        // 通常動作（クロックの立ち上がりエッジ）
        else begin
            // 入力 d の値を q に転送（データ保持）
            q <= d;
        end
    end

endmodule